#!/usr/bin/env python3
# Writes the Fix16 sine table that the port (anodyne/fix16_sin.h) and the C# (Fix.cs's SinTable) both use: sin of a
# quarter turn in 1024 steps, rounded to 16.16 (halves away from zero). Generated once and checked in on both sides,
# so neither game's own sin() decides the numbers.
#   python3 gen_sin.py <out.h> [<out.cs>]
import math
import sys

N = 1024
vals = []
for i in range(N + 1):
    v = math.sin(math.pi / 2 * i / N) * 65536
    vals.append(int(math.floor(v + 0.5)))

def rows(indent):
    out = []
    for i in range(0, len(vals), 12):
        out.append(indent + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
    return "\n".join(out)

with open(sys.argv[1], "w") as f:
    f.write("// Generated by tools/fix16/gen_sin.py: sin(i / 1024 * pi / 2) in 16.16, i = 0..1024. Don't edit.\n")
    f.write("#pragma once\n\n#include <stdint.h>\n\n")
    f.write("constexpr int32_t kFix16Sin[%d] = {\n%s\n};\n" % (N + 1, rows("    ")))
if len(sys.argv) > 2:
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by anodyne-cpp's tools/fix16/gen_sin.py: sin(i / 1024 * pi / 2) in 16.16, i = 0..1024.\n")
        f.write("// Don't edit.\nnamespace AnodyneSharp.Utilities\n{\n    public partial struct Fix\n    {\n")
        f.write("        internal static readonly int[] SinTable = {\n%s\n        };\n    }\n}\n" % rows("            "))
