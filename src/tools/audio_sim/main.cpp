static std::vector<uint8_t> ReadFile(const std::string& path)
{
    std::ifstream f(path, std::ios::binary);
    if (!f)
    {
        return {};
    }
    return std::vector<uint8_t>((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
}

// One simulated VBlank of the real AudioManager_OnVBlank()'s BGM stream
// (BGM alone - ambience/SFX mixing isn't what's under test here),
// reimplementing only the ACCUMULATOR SEQUENCING (which
// audio_manager.cpp also does inline, not through a shared function) -
// everything else (DecodeCursor_*, ComputeTimerDivisor/Reload/
// SamplesPerVBlank) is the identical shared code.
struct BgmSim final
{
    DecodeCursor cursor;
    uint32_t samplesPerVBlankQ16 = 0;
    uint32_t accumulatorQ16 = 0;
    bool up2 = false; // track is at half the output rate -> Mix16Up2, as MixStream() does

    void Start(const AudioTrackData* track)
    {
        DecodeCursor_Start(&cursor, track, true);
        uint32_t divisor = ComputeTimerDivisor(AUDIO_OUTPUT_SAMPLE_RATE);
        samplesPerVBlankQ16 = ComputeSamplesPerVBlankQ16FromDivisor(divisor);
        accumulatorQ16 = 0;
        up2 = track->sampleRate != AUDIO_OUTPUT_SAMPLE_RATE;
    }

    // Appends this VBlank's worth of samples to `out`. Returns how many were
    // produced (can be less than requested only if the cursor stopped,
    // which shouldn't happen here since we always loop=true).
    uint32_t StepOneVBlank(std::vector<int16_t>& out)
    {
        accumulatorQ16 += samplesPerVBlankQ16;
        uint32_t n = accumulatorQ16 >> 16;
        accumulatorQ16 &= 0xFFFFu;

        std::vector<int32_t> accum(n, 0);
        uint32_t got = up2 ? DecodeCursor_Mix16Up2(&cursor, accum.data(), n) : DecodeCursor_Mix16(&cursor, accum.data(), n);
        for (uint32_t i = 0; i < got; i++)
        {
            out.push_back(static_cast<int16_t>(accum[i]));
        }
        return got;
    }
};

// Reference decode of a whole track (first play, no looping) via upstream
// qoa.h's qoa_decode_frame, frame by frame - deliberately NOT through
// DecodeCursor, so the streaming slice decoder under test is checked against
// an independent implementation rather than against itself.
static std::vector<int16_t> DecodeLinear(const AudioTrackData* track, uint32_t* loopStartSampleOffset)
{
    std::vector<int16_t> out;
    std::vector<short> frame(AUDIO_MAX_FRAME_SAMPLES);
    qoa_desc qoa = {};
    qoa.channels = 1;
    qoa.samplerate = track->sampleRate;
    *loopStartSampleOffset = 0;
    for (uint32_t f = 0; f < track->frameCount; f++)
    {
        if (f == track->loopStartFrame)
        {
            *loopStartSampleOffset = static_cast<uint32_t>(out.size());
        }
        unsigned int frameLen = 0;
        qoa_decode_frame(g_AudioBlobBase + track->frames[f].offset, track->frames[f].length, &qoa, frame.data(),
                         &frameLen);
        for (unsigned int i = 0; i < frameLen; i++)
        {
            out.push_back(frame[i]);
        }
    }
    return out;
}

struct TestResult final
{
    bool pass = true;
    std::string detail;
};

static TestResult TestTrack(const AudioTrackData* track, int loopIterationsToVerify)
{
    TestResult result;

    uint32_t loopOffset = 0;
    std::vector<int16_t> reference = DecodeLinear(track, &loopOffset);
    if (reference.size() != track->totalSamples)
    {
        result.pass = false;
        result.detail = "linear decode produced " + std::to_string(reference.size()) + " samples, expected " +
                         std::to_string(track->totalSamples);
        return result;
    }

    if (!track->loopEnabled)
    {
        loopOffset = 0;
    }
    uint32_t loopedLen = static_cast<uint32_t>(reference.size()) - loopOffset;

    // The expected sample at any index i >= 0: the first play is
    // reference[0..totalSamples), every play after that is
    // reference[loopOffset..totalSamples) repeating. Expressed as a
    // function rather than a pre-built buffer so the simulation can run to
    // whatever length it naturally lands on (each VBlank step produces a
    // variable ~176-ish samples) with nothing trimmed or padded.
    auto nativeAt = [&](uint64_t i) -> int32_t
    {
        if (i < reference.size())
        {
            return reference[i];
        }
        uint64_t intoLoop = (i - reference.size()) % loopedLen;
        return reference[loopOffset + intoLoop];
    };

    // At the OUTPUT rate: a half-rate track's sample j becomes outputs 2j
    // (midpoint with sample j-1, or with silence before the first) and 2j+1.
    const bool up2 = track->sampleRate != AUDIO_OUTPUT_SAMPLE_RATE;
    auto expectedAt = [&](uint64_t i) -> int16_t
    {
        if (!up2)
        {
            return static_cast<int16_t>(nativeAt(i));
        }
        uint64_t j = i / 2;
        if (i & 1)
        {
            return static_cast<int16_t>(nativeAt(j));
        }
        int32_t prev = (j == 0) ? 0 : nativeAt(j - 1);
        return static_cast<int16_t>((prev + nativeAt(j)) >> 1);
    };

    uint64_t targetSamples =
        (static_cast<uint64_t>(reference.size()) + static_cast<uint64_t>(loopIterationsToVerify - 1) * loopedLen) *
        (up2 ? 2 : 1);

    BgmSim sim;
    sim.Start(track);
    std::vector<int16_t> actual;
    actual.reserve(targetSamples);
    uint64_t vblanks = 0;
    while (actual.size() < targetSamples)
    {
        uint32_t got = sim.StepOneVBlank(actual);
        vblanks++;
        if (got == 0)
        {
            result.pass = false;
            result.detail = "cursor stopped producing samples at vblank " + std::to_string(vblanks) +
                             " (" + std::to_string(actual.size()) + "/" + std::to_string(targetSamples) +
                             " samples) - should loop forever, never stop";
            return result;
        }
    }

    // --- Rate accuracy check ---
    double expectedSeconds = static_cast<double>(actual.size()) / static_cast<double>(AUDIO_OUTPUT_SAMPLE_RATE);
    double simulatedSeconds = static_cast<double>(vblanks) / (16777216.0 / 280896.0);
    double rateErrorPct = 100.0 * (simulatedSeconds - expectedSeconds) / expectedSeconds;
    if (std::abs(rateErrorPct) > 0.01) // 0.01% - should be exact given the divisor-consistent design
    {
        result.pass = false;
        result.detail = "rate drift: " + std::to_string(vblanks) + " VBlanks (" + std::to_string(simulatedSeconds) +
                         "s real time) produced " + std::to_string(actual.size()) + " samples (" +
                         std::to_string(expectedSeconds) + "s at " + std::to_string(AUDIO_OUTPUT_SAMPLE_RATE) +
                         "Hz) - error " + std::to_string(rateErrorPct) + "%";
        return result;
    }

    // --- Sequencing/loop correctness check ---
    if (actual.size() < targetSamples)
    {
        result.pass = false;
        result.detail = "produced only " + std::to_string(actual.size()) + " samples, wanted at least " +
                         std::to_string(targetSamples);
        return result;
    }
    for (size_t i = 0; i < actual.size(); i++)
    {
        int16_t exp = expectedAt(i);
        if (actual[i] != exp)
        {
            result.pass = false;
            result.detail = "first mismatch at sample " + std::to_string(i) + "/" + std::to_string(actual.size()) +
                             " (" + std::to_string(100.0 * i / actual.size()) + "% through, " +
                             std::to_string(i / static_cast<double>(track->totalSamples * (up2 ? 2 : 1))) +
                             " loop-lengths in): got " + std::to_string(static_cast<int>(actual[i])) +
                             ", expected " + std::to_string(static_cast<int>(exp));
            return result;
        }
    }

    result.detail = std::to_string(vblanks) + " VBlanks simulated, " + std::to_string(actual.size()) +
                     " samples, " + std::to_string(loopIterationsToVerify) + " loop plays verified, rate error " +
                     std::to_string(rateErrorPct) + "%";
    return result;
}

int main(int argc, char** argv)
{
    std::string toolsDir = (argc > 1) ? argv[1] : "../../build/tools";
    int loopIterations = (argc > 2) ? std::atoi(argv[2]) : 3;

    std::vector<uint8_t> blob = ReadFile(toolsDir + "/audio_blob.bin");
    if (blob.empty())
    {
        printf("Failed to read %s/audio_blob.bin\n", toolsDir.c_str());
        return 1;
    }
    g_AudioBlobBase = blob.data();

    int failures = 0;
    for (uint32_t i = 0; i < kBgmTracksCount; i++)
    {
        TestResult r = TestTrack(&kBgmTracks[i], loopIterations);
        printf("[%s] %-20s %s\n", r.pass ? "PASS" : "FAIL", kBgmTracks[i].name, r.detail.c_str());
        if (!r.pass)
        {
            failures++;
        }
    }

    printf("\n%d/%zu tracks passed\n", (int)kBgmTracksCount - failures, (size_t)kBgmTracksCount);
    return failures == 0 ? 0 : 1;
}
