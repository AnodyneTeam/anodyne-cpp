// Host-side timing/sequencing simulator for the GBA audio pipeline.
//
// This does NOT model CPU decode cost or claim to catch every real-hardware
// issue (see the session notes on why: no QEMU/gdb-sim/mGBA-Python-bindings
// available without sudo here). What it DOES verify, using the exact
// production decode/timing code (audio_decode_core.cpp, compiled unchanged -
// not reimplemented) rather than a guess about what it does:
//
//   1. Rate accuracy: does the Bresenham-accumulated refill schedule
//      produce, over a long simulated run, exactly as many samples as the
//      configured sample rate implies for that much simulated time? (This
//      is the class of bug behind the "gets worse over time" pitch-drift
//      regression - divisor/accumulator inconsistency.)
//   2. Sequencing correctness: does calling DecodeCursor_Mix16 in small,
//      VBlank-sized chunks (as the real ISR does) produce byte-identical
//      output to a linear decode of the same track by upstream qoa.h's
//      qoa_decode_frame? (Chunking bugs - dropped/duplicated/misordered
//      samples at frame/slice boundaries - and any divergence of the
//      streaming slice decoder from the reference QOA implementation.)
//   3. Loop-wraparound correctness: after the track's natural end, does
//      playback resume at exactly loopStartFrame's sample offset and keep
//      matching the reference, indefinitely, without drift? (The "some
//      part just loops forever" class of bug, at least the sequencing half
//      of it - not the DMA-hardware half.)
//
// Explicitly NOT covered: real CPU decode latency vs VBlank budget, actual
// DMA/FIFO hardware timing, register correctness, anything requiring real
// instruction execution - for those, capture real FIFO output from the
// instrumented mGBA fork (src/tools/mgba, ANODYNE_FIFO_LOG) and diff it.

#include "../../anodyne/audio_decode_core.hpp"

