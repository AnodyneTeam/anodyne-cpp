#!/usr/bin/env python3
"""Converts the data-only GNU as files of libtonc (sin_lut.s, div_lut.s, the fonts) into C, so the simulator can
link them on the host.

  s2c.py <out.c> <in.s>...

Each label becomes a C object of the same name. A label whose data is plain numbers becomes a byte array (little
endian, 4-byte aligned) so any C declaration of it reads the same bytes as on the GBA. A label whose .word list
names another symbol (a TFont: `.word glyphs, 0, 0`) is a struct of pointers: every .word of it becomes a
pointer-sized field, .hword a u16 and .byte a u8, which matches the C struct's layout on a 64-bit host."""
import re
import sys


def parse(path):
    labels = []  # (name, [(kind, value)])
    cur = None
    with open(path, encoding="latin-1") as f:
        for raw in f:
            line = raw.split("@", 1)[0].strip()
            if not line:
                continue
            m = re.match(r"^([A-Za-z_.$][\w.$]*):(.*)$", line)
            if m:
                cur = (m.group(1), [])
                labels.append(cur)
                line = m.group(2).strip()
                if not line:
                    continue
            m = re.match(r"^\.(word|hword|short|byte|long|int)\s+(.*)$", line)
            if not m or cur is None:
                continue
            kind = {"long": "word", "int": "word", "short": "hword"}.get(m.group(1), m.group(1))
            for item in m.group(2).split(","):
                item = item.strip()
                if item:
                    cur[1].append((kind, item))
    return labels


def number(text):
    return int(text, 0)


def is_symbol(text):
    return re.match(r"^[A-Za-z_][\w]*$", text) is not None


def main():
    out, inputs = sys.argv[1], sys.argv[2:]
    lines = ["// Generated by s2c.py from libtonc's data-only assembly. Do not edit.", "#include <stdint.h>", ""]
    for path in inputs:
        for name, items in parse(path):
            if not items:
                continue
            if any(k == "word" and is_symbol(v) for k, v in items):
                fields, values = [], []
                for i, (k, v) in enumerate(items):
                    if k == "word":
                        fields.append(f"const void* f{i};")
                        values.append(f"&{v}" if is_symbol(v) else f"(const void*){number(v)}")
                        if is_symbol(v):
                            lines.insert(2, f"extern const uint8_t {v}[];")
                    elif k == "hword":
                        fields.append(f"uint16_t f{i};")
                        values.append(str(number(v)))
                    else:
                        fields.append(f"uint8_t f{i};")
                        values.append(str(number(v)))
                lines.append(f"const struct {{ {' '.join(fields)} }} {name} = {{ {', '.join(values)} }};")
                continue
            data = bytearray()
            for k, v in items:
                size = {"word": 4, "hword": 2, "byte": 1}[k]
                data += (number(v) & ((1 << (8 * size)) - 1)).to_bytes(size, "little")
            body = ",".join(str(b) for b in data)
            lines.append(f"__attribute__((aligned(4))) const uint8_t {name}[{len(data)}] = {{{body}}};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


main()
